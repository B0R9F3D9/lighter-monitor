function injectVersionMeta(html: string, version: string): string {
  if (html.includes('<meta name="version"')) return html;
  return html.replace("<head>", `<head><meta name="version" content="${version}">`);
}

async function readHtmlFile(filePath: string, maxRetries = 10): Promise<string> {
  for (let i = 0; i < maxRetries; i++) {
    if (fs.existsSync(filePath)) {
      try {
        return fs.readFileSync(filePath, "utf-8");
      } catch {
        await new Promise((r) => setTimeout(r, 100));
      }
    } else {
      await new Promise((r) => setTimeout(r, 100));
    }
  }
  throw new Error(`File not found or unreadable: ${filePath}`);
}

