import { build } from "vite";
import tailwindcss from "@tailwindcss/vite";
import { minify } from "html-minifier-terser";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const rootDir = process.cwd();
const outDir = path.resolve(rootDir, "dist");

console.log(
  "🚀 Building frontend with Vite 8 + Tailwind v4 (Hub Router + Spread Monitor + Analytics Terminal)...",
);
await build({
  root: path.resolve(rootDir, "web"),
  base: "/",
  plugins: [tailwindcss()],
  build: {
    outDir,
    emptyOutDir: true,
    minify: "esbuild",
    cssMinify: "esbuild",
    rollupOptions: {
      input: {
        index: path.resolve(rootDir, "web/index.html"),
        spread: path.resolve(rootDir, "web/spread.html"),
        analytics: path.resolve(rootDir, "web/analytics.html"),
      },
    },
  },
});

const minifyConfig = {
  collapseWhitespace: true,
  removeComments: true,
  removeRedundantAttributes: true,
  useShortDoctype: true,
  minifyCSS: false,
  minifyJS: false,
};

console.log("🗜️  Minifying HTML markup with html-minifier-terser...");

// 1. Minify Hub Router HTML (/)
const hubHtmlPath = path.resolve(outDir, "index.html");
const rawHubHtml = fs.readFileSync(hubHtmlPath, "utf-8");
const minifiedHubHtml = await minify(rawHubHtml, minifyConfig);
fs.writeFileSync(hubHtmlPath, minifiedHubHtml, "utf-8");
fs.writeFileSync(path.resolve(rootDir, "src/hub.html"), minifiedHubHtml, "utf-8");

// 2. Minify Spread Monitor HTML (/spread)
const spreadHtmlPath = path.resolve(outDir, "spread.html");
const rawSpreadHtml = fs.readFileSync(spreadHtmlPath, "utf-8");
const minifiedSpreadHtml = await minify(rawSpreadHtml, minifyConfig);
fs.writeFileSync(spreadHtmlPath, minifiedSpreadHtml, "utf-8");
fs.writeFileSync(path.resolve(rootDir, "src/spread.html"), minifiedSpreadHtml, "utf-8");

// 3. Minify Analytics Terminal HTML (/analytics)
const analyticsHtmlPath = path.resolve(outDir, "analytics.html");
const rawAnalyticsHtml = fs.readFileSync(analyticsHtmlPath, "utf-8");
const minifiedAnalyticsHtml = await minify(rawAnalyticsHtml, minifyConfig);
fs.writeFileSync(analyticsHtmlPath, minifiedAnalyticsHtml, "utf-8");
fs.writeFileSync(path.resolve(rootDir, "src/analytics.html"), minifiedAnalyticsHtml, "utf-8");

function getContentType(file: string): string {
  const ext = path.extname(file).toLowerCase();
  switch (ext) {
    case ".css":
      return "text/css; charset=utf-8";
    case ".js":
      return "application/javascript; charset=utf-8";
    case ".svg":
      return "image/svg+xml";
    case ".png":
      return "image/png";
    case ".ico":
      return "image/x-icon";
    case ".html":
      return "text/html; charset=utf-8";
    default:
      return "application/octet-stream";
  }
}

function isBinaryFile(file: string): boolean {
  const ext = path.extname(file).toLowerCase();
  return ext === ".png" || ext === ".ico" || ext === ".webp" || ext === ".jpg";
}

export interface AssetEntry {
  content: string;
  contentType: string;
  hash: string;
  isBase64?: boolean;
}

const assetsMap: Record<string, AssetEntry> = {};

function registerAsset(filePath: string, fileName: string) {
  const binary = isBinaryFile(fileName);
  const raw = fs.readFileSync(filePath);
  const content = binary ? raw.toString("base64") : raw.toString("utf-8");
  const contentType = getContentType(fileName);
  const hash = crypto.createHash("sha256").update(raw).digest("hex").slice(0, 10);

  assetsMap[fileName] = {
    content,
    contentType,
    hash,
    ...(binary ? { isBase64: true } : {}),
  };
}

// 1. Files in dist/assets/
const assetsDir = path.resolve(outDir, "assets");
if (fs.existsSync(assetsDir)) {
  for (const file of fs.readdirSync(assetsDir)) {
    registerAsset(path.resolve(assetsDir, file), file);
  }
}

// 2. Public static files in dist/ (favicons, logos)
for (const file of fs.readdirSync(outDir)) {
  if (
    file === "index.html" ||
    file === "spread.html" ||
    file === "analytics.html" ||
    file === "assets"
  )
    continue;
  const filePath = path.resolve(outDir, file);
  if (fs.statSync(filePath).isFile()) {
    registerAsset(filePath, file);
  }
}

const hubHtmlHash = crypto.createHash("sha256").update(minifiedHubHtml).digest("hex").slice(0, 10);
const spreadHtmlHash = crypto
  .createHash("sha256")
  .update(minifiedSpreadHtml)
  .digest("hex")
  .slice(0, 10);
const analyticsHtmlHash = crypto
  .createHash("sha256")
  .update(minifiedAnalyticsHtml)
  .digest("hex")
  .slice(0, 10);

const assetsModuleContent = `// Auto-generated by scripts/build_web.ts. Do not edit directly.
export const HUB_HTML = ${JSON.stringify(minifiedHubHtml)};
export const HUB_HTML_HASH = ${JSON.stringify(hubHtmlHash)};

export const SPREAD_HTML = ${JSON.stringify(minifiedSpreadHtml)};
export const SPREAD_HTML_HASH = ${JSON.stringify(spreadHtmlHash)};

export const ANALYTICS_HTML = ${JSON.stringify(minifiedAnalyticsHtml)};
export const ANALYTICS_HTML_HASH = ${JSON.stringify(analyticsHtmlHash)};

export interface SpreadAsset {
  content: string;
  contentType: string;
  hash: string;
  isBase64?: boolean;
}

export const SPREAD_ASSETS: Record<string, SpreadAsset> = ${JSON.stringify(assetsMap, null, 2)};
`;

fs.writeFileSync(path.resolve(rootDir, "src/spread_assets.ts"), assetsModuleContent, "utf-8");

console.log("✓ Hub Router HTML minified:", minifiedHubHtml.length, "bytes");
console.log("✓ Spread HTML minified:", minifiedSpreadHtml.length, "bytes");
console.log("✓ Analytics HTML minified:", minifiedAnalyticsHtml.length, "bytes");
console.log("✓ Registered assets:", Object.keys(assetsMap).join(", "));
console.log(
  "✓ Generated src/spread_assets.ts & synced src/hub.html / src/spread.html / src/analytics.html",
);
